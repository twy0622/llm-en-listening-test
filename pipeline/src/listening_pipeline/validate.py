BANNED = re.compile(
    r"\b(politics?|elections?|religio(n|us)|church|mosque|synagogue|cancer|diagnos(is|ed)|"
    r"suicide|abortion|gun|guns|weapon|war|sexual|porn|divorce)\b",
    re.IGNORECASE,
)
MARKDOWN = re.compile(r"(\*\*|__|^#{1,6}\s|\[[^\]]+\]\([^)]+\))", re.MULTILINE)
EMOJI = re.compile(
    "[" "\U0001F300-\U0001FAFF" "\U00002700-\U000027BF" "\U0001F1E6-\U0001F1FF" "]"
)
AI_SMELL = re.compile(
    r"\b(as an ai|language model|generated by|this is an exam|listening test)\b", re.IGNORECASE
)
GAP_BLANK = re.compile(r"_{3,}")
SENTENCE_END = re.compile(r"[.!?](?:\s|$)")


@dataclass
class ValidationResult:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors

    def extend(self, other: ValidationResult) -> None:
        self.errors.extend(other.errors)
        self.warnings.extend(other.warnings)


class PackValidationError(ValueError):
    def __init__(self, errors: list[str]) -> None:
        super().__init__("Pack validation failed:\n- " + "\n- ".join(errors))
        self.errors = errors


def parse_dialogue_turns(transcript: str) -> tuple[list[tuple[str, str]], list[str]]:
    """Return (turns, errors). Accepts common label variants but normalises to A/B."""
    turns: list[tuple[str, str]] = []
    errors: list[str] = []
    for raw_line in transcript.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        cleaned = line.replace("**", "").replace("__", "")
        match = re.match(r"^(?:Speaker\s*)?([AB])\s*[:：]\s*(.+)$", cleaned, re.IGNORECASE)
        if not match:
            errors.append(f"Dialogue line is not a clean A:/B: turn: {line[:90]!r}")
            continue
        speaker = match.group(1).upper()
        text = match.group(2).strip()
        if not text:
            errors.append(f"Empty turn for speaker {speaker}")
            continue
        turns.append((speaker, text))
    return turns, errors


def _check_common_text(text: str, label: str) -> list[str]:
    errors: list[str] = []
    if MARKDOWN.search(text):
        errors.append(f"{label}: markdown is not allowed")
    if EMOJI.search(text):
        errors.append(f"{label}: emoji are not allowed")
    if AI_SMELL.search(text):
        errors.append(f"{label}: contains meta/exam language")
    banned = BANNED.search(text)
    if banned:
        errors.append(f"{label}: sensitive topic term {banned.group(0)!r}")
    return errors


def _sentence_count(text: str) -> int:
    return len(SENTENCE_END.findall(text.strip())) or (1 if text.strip() else 0)


def _validate_monologue(raw: RawPassage) -> ValidationResult:
    result = ValidationResult()
    transcript = raw.transcript.strip()
    paragraphs = [p.strip() for p in re.split(r"\n{2,}", transcript) if p.strip()]
    if not 2 <= len(paragraphs) <= 7:
        result.errors.append(f"Monologue should have 3–5 paragraphs (got {len(paragraphs)})")
    if re.search(r"^\s*[AB]\s*[:：]", transcript, re.MULTILINE):
        result.errors.append("Monologue must not contain speaker labels")
    if len(re.findall(r"\b(I|I'm|I've|my|me)\b", transcript, re.IGNORECASE)) < 3:
        result.errors.append("Monologue should be first person and personal")
    for index, paragraph in enumerate(paragraphs, start=1):
        words = word_count(paragraph)
        if words > 85:
            result.errors.append(f"Monologue paragraph {index} is too long ({words} words)")
    if raw.gender not in ("male", "female"):
        result.errors.append("Monologue must specify a voice gender (male or female)")
    return result


def _validate_dialogue(raw: RawPassage) -> ValidationResult:
    result = ValidationResult()
    turns, parse_errors = parse_dialogue_turns(raw.transcript)
    result.errors.extend(parse_errors)
    if not 8 <= len(turns) <= 20:
        result.errors.append(f"Dialogue should have 10–16 turns (got {len(turns)})")
    if turns:
        speakers = [speaker for speaker, _ in turns]
        for index in range(1, len(speakers)):
            if speakers[index] == speakers[index - 1]:
                result.errors.append(
                    f"Dialogue turns should alternate; found {speakers[index]} twice in a row"
                )
                break
        if set(speakers) != {"A", "B"}:
            result.errors.append("Dialogue needs both speaker A and speaker B")
        for index, (speaker, text) in enumerate(turns, start=1):
            words = word_count(text)
            if words < 2 or words > 70:
                result.errors.append(
                    f"Dialogue turn {index} ({speaker}) should be 3–55 words (got {words})"
                )
    if re.search(r"^\s*[C-Z]\s*[:：]", raw.transcript, re.MULTILINE):
        result.errors.append("Dialogue can only have speakers A and B")
    return result


def _validate_question(question, transcript: str, index: int) -> list[str]:
    errors: list[str] = []
    errors.extend(_check_common_text(question.prompt, f"Question {index} prompt"))
    errors.extend(_check_common_text(question.explanation, f"Question {index} explanation"))

    if isinstance(question, LlmMcq):
        key = question.answer.key
        answer_text = next(
            (choice.text for choice in question.choices if choice.key == key), ""
        )
        if not answer_text:
            errors.append(f"Question {index}: answer key is missing from the choices")
        lowered = [choice.text.lower() for choice in question.choices]
        if any("all of the above" in text or "none of the above" in text for text in lowered):
            errors.append(f"Question {index}: avoid all/none-of-the-above options")
        if len({normalize_answer(text) for text in lowered}) != 4:
            errors.append(f"Question {index}: choices are not distinct after normalisation")
        # The answer should not be given away by being the longest option every time.
        if answer_text and all(len(answer_text) > len(choice.text) * 2 for choice in question.choices if choice.key != key):
            errors.append(f"Question {index}: the correct choice is conspicuously the longest")
        if answer_text and len(answer_text.split()) > 18:
            errors.append(f"Question {index}: MCQ choices should be short")

    elif isinstance(question, LlmGapfill):
        if not GAP_BLANK.search(question.prompt):
            errors.append(f"Question {index}: gap-fill prompt needs ___")
        primary = question.answer.accepted[0]
        if word_count(primary) > 4:
            errors.append(f"Question {index}: gap-fill answer is too long ({word_count(primary)} words)")
        if not contains_answer(transcript, primary):
            errors.append(
                f"Question {index}: gap-fill answer {primary!r} does not appear in the transcript"
            )
        normalized_prompt = normalize_answer(question.prompt)
        normalized_answer = normalize_answer(primary)
        if normalized_answer and normalized_answer in normalized_prompt:
            errors.append(f"Question {index}: the gap-fill answer is printed in the prompt")
        variants = [normalize_answer(value) for value in question.answer.accepted]
        if len(set(variants)) != len(variants):
            errors.append(f"Question {index}: duplicate accepted gap-fill variants")

    elif isinstance(question, LlmSubjective):
        expected_words = word_count(question.answer.expected)
        if expected_words < 8:
            errors.append(f"Question {index}: expected answer is too short ({expected_words} words)")
        if _sentence_count(question.answer.expected) < 2:
            errors.append(f"Question {index}: expected answer should be 2–4 sentences")
        if len(question.answer.rubric) < 2:
            errors.append(f"Question {index}: rubric needs at least two criteria")
        if len(question.answer.rubric) > 4:
            errors.append(f"Question {index}: rubric should have at most four criteria")

    for skill in [question.skill]:
        if skill not in {
            "gist",
            "detail",
            "inference",
            "attitude",
            "vocabulary",
            "function",
            "organization",
        }:
            errors.append(f"Question {index}: unknown skill {skill!r}")

    return errors


def validate_raw_passage(
    raw: RawPassage,
    card: TopicCard,
    level: str,
    *,
    expected_type: str | None = None,
) -> ValidationResult:
    result = ValidationResult()
    transcript = raw.transcript.strip()
    kind = card.kind
    if expected_type and kind != expected_type:
        result.errors.append(f"Scenario card is {kind}, expected {expected_type}")

    min_words, max_words = WORD_TARGETS[kind][level]  # type: ignore[index]
    words = word_count(transcript)
    if not int(min_words * 0.9) <= words <= int(max_words * 1.12):
        result.errors.append(
            f"Transcript is {words} words; target for {level} {kind} is {min_words}–{max_words}"
        )

    result.errors.extend(_check_common_text(transcript, "Transcript"))
    if "?" in transcript and kind == "monologue" and transcript.count("?") > 3:
        result.warnings.append("Monologue asks many questions; check it still sounds like speech")

    if len(raw.title) < 3 or len(raw.title) > 80:
        result.errors.append("Title should be 3–8 words")
    if len(raw.title.split()) > 10:
        result.errors.append("Title is too long")

    if kind == "monologue":
        result.extend(_validate_monologue(raw))
    else:
        result.extend(_validate_dialogue(raw))

    if len(raw.questions) != 5:
        result.errors.append(f"Exactly 5 questions are required (got {len(raw.questions)})")
    expected_order = ["mcq", "gapfill", "mcq", "gapfill", "subjective"]
    actual_order = [question.type for question in raw.questions]
    if actual_order != expected_order:
        result.errors.append(
            f"Question order should be {expected_order}, got {actual_order}"
        )

    skills = {question.skill for question in raw.questions}
    if len(skills) < 3:
        result.errors.append("Use at least three different skill tags across the questions")
    if len({normalize_answer(question.prompt) for question in raw.questions}) != len(raw.questions):
        result.errors.append("Question prompts must be distinct")

    for index, question in enumerate(raw.questions, start=1):
        result.errors.extend(_validate_question(question, transcript, index))

    # A light level sanity check; not a CEFR classifier.
    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", transcript) if s.strip()]
    if sentences:
        average = sum(word_count(sentence) for sentence in sentences) / len(sentences)
        if level == "A2" and average > 20:
            result.warnings.append(f"Average sentence length is {average:.1f}; A2 may be too dense")
        if level in ("B2", "C1") and average < 9:
            result.warnings.append(f"Average sentence length is {average:.1f}; {level} may be too simple")

    return result


def validate_pack(pack: TestPack) -> ValidationResult:
    result = ValidationResult()
    try:
        datetime.fromisoformat(pack.created_at.replace("Z", "+00:00"))
    except ValueError:
        result.errors.append("createdAt must be an ISO-8601 timestamp")

    if pack.duration_sec < 120:
        result.errors.append("durationSec must be at least 120 seconds")
    if not pack.passages:
        result.errors.append("A pack needs at least one passage")

    seen_topics: set[str] = set()
    for passage in pack.passages:
        if passage.audio.key and not passage.audio.key.startswith(f"audio/{pack.id}/"):
            result.errors.append(
                f"Passage {passage.id}: audio key must start with audio/{pack.id}/"
            )
        if passage.audio.duration_sec > 900:
            result.errors.append(f"Passage {passage.id}: audio is longer than 15 minutes")
        if passage.topic in seen_topics:
            result.errors.append(f"Passage {passage.id}: duplicate topic")
        seen_topics.add(passage.topic)
        if passage.topic_card and passage.topic_card.level != pack.level:
            result.errors.append(f"Passage {passage.id}: topic card level does not match pack")
        if len(passage.questions) != 5:
            result.errors.append(f"Passage {passage.id}: expected 5 questions")
        if [q.position for q in passage.questions] != list(range(1, len(passage.questions) + 1)):
            result.errors.append(f"Passage {passage.id}: question positions must be contiguous")
        for question in passage.questions:
            if isinstance(question, PackGapfill):
                primary = question.answer.accepted[0]
                if not contains_answer(passage.transcript, primary):
                    result.errors.append(
                        f"Question {question.id}: gap-fill answer does not appear in transcript"
                    )
            if question.points <= 0:
                result.errors.append(f"Question {question.id}: points must be positive")

    answers = [
        question.answer.key
        for passage in pack.passages
        for question in passage.questions
        if isinstance(question, PackMcq)
    ]
    if len(answers) >= 4 and len(set(answers)) == 1:
        result.warnings.append("All MCQ answers share the same key; shuffle them before publishing")

    return result


def assert_valid_pack(pack: TestPack) -> None:
    result = validate_pack(pack)
    if not result.ok:
        raise PackValidationError(result.errors)
